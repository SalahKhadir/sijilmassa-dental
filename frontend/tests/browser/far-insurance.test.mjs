import assert from "node:assert/strict";
import { before, after, test } from "node:test";
import { PDFDocument } from "pdf-lib";
import { browserHarness } from "./browser-harness.mjs";
const harness = browserHarness({ port: 3109 });
before(harness.start);
after(harness.stop);
test("FAR requires explicit symbols and approval, preserves origin, downloads, prints, saves and revokes stale previews", async () => {
  const { value, page, errors, external } = await harness.context();
  try {
    await page.goto(`${harness.baseURL}/documents/assurances/draft-ins-demo-003`);
    const chart = page.getByRole("region", { name: "Schéma dentaire", exact: true });
    const pdf = page.getByRole("region", { name: "PDF FAR", exact: true });
    const preview = pdf.getByRole("button", { name: "Prévisualiser la feuille FAR", exact: true });
    await preview.click();
    await pdf.getByRole("alert").filter({ hasText: "INPE" }).waitFor();
    await page.locator("#far-inpe").fill("123456789");
    await page.locator("#far-prospectus").fill("0");
    assert.equal(await chart.getByRole("checkbox").count(), 52);
    assert.equal(await chart.locator("[data-far-tooth]").count(), 0);
    await chart.getByRole("checkbox", { name: "Sélectionner la dent FDI 36", exact: true }).check();
    await chart.getByRole("checkbox", { name: "Sélectionner la dent FDI 51", exact: true }).check();
    await preview.click();
    await pdf.getByRole("alert").filter({ hasText: "Cercle ou Croix" }).waitFor();
    await page.getByLabel("Symbole FAR de la dent 36", { exact: true }).selectOption("CERCLE");
    await page.getByLabel("Symbole FAR de la dent 51", { exact: true }).selectOption("CROIX");
    await preview.click();
    await pdf.getByRole("alert").filter({ hasText: "confirmer les symboles" }).waitFor();
    const approval = page.getByRole("checkbox", { name: "Je confirme, en tant que dentiste, les dents et les symboles selon la notice FAR.", exact: true });
    await approval.check(); await preview.click();
    const link = pdf.getByRole("link", { name: "Télécharger le PDF", exact: true });
    await link.waitFor(); const oldUrl = await link.getAttribute("href");
    const bytes = await page.evaluate(async url => Array.from(new Uint8Array(await (await fetch(url)).arrayBuffer())), oldUrl);
    const document = await PDFDocument.load(new Uint8Array(bytes));
    assert.equal(document.getPageCount(),2);
    assert.equal(document.getPages()[0].getWidth(),842.25);
    assert(Math.abs(document.getPages()[1].getCropBox().y-8.580014)<.0001);
    assert.equal(document.getPages()[1].getRotation().angle,0);
    const download = page.waitForEvent("download"); await link.click();
    assert.equal((await download).suggestedFilename(),"feuille-soins-far.pdf");
    await page.waitForFunction(() => !Array.from(document.querySelectorAll("button")).find(b=>b.textContent==="Imprimer")?.disabled);
    await page.evaluate(() => {
      window.__farPrintCalls=0;
      document.querySelector('iframe[title*="PDF FAR"]').contentWindow.print=()=>window.__farPrintCalls++;
    });
    await pdf.getByRole("button",{name:"Imprimer",exact:true}).click();
    assert.equal(await page.evaluate(()=>window.__farPrintCalls),1);
    await page.getByLabel("Symbole FAR de la dent 51",{exact:true}).selectOption("CERCLE");
    assert.equal(await link.count(),0); assert.equal(await approval.isChecked(),false);
    assert(await page.evaluate(async url=>{try {await fetch(url);return false;}catch{return true;}},oldUrl));
    await approval.check();
    await page.getByPlaceholder("Description de l'acte...").first().fill("Traitement fictif");
    assert.equal(await approval.isChecked(),false);
    await chart.getByRole("button",{name:"Effacer les marques",exact:true}).click();
    assert.equal(await chart.locator("[data-far-tooth]").count(),0);
    await chart.getByRole("checkbox",{name:"Sélectionner la dent FDI 36",exact:true}).check();
    await page.getByLabel("Symbole FAR de la dent 36",{exact:true}).selectOption("CERCLE");
    await approval.check();
    await page.screenshot({path:"/tmp/far-review/browser-far.png",fullPage:true});
    await page.getByRole("button",{name:"Enregistrer en brouillon",exact:true}).click();
    await page.waitForURL("**/demo/patients/patient-demo-003");
    await page.locator('a[href="/documents/assurances/draft-ins-demo-003"]').click();
    await chart.waitFor(); assert(await approval.isChecked());
    assert.equal(await page.getByLabel("Symbole FAR de la dent 36",{exact:true}).inputValue(),"CERCLE");
    assert.equal(await page.locator("#far-inpe").inputValue(),"123456789");
    assert.equal(await page.locator("#far-prospectus").inputValue(),"0");
    assert.deepEqual(errors,[]);
    assert.deepEqual(external.filter(url=>!url.startsWith("blob:")),[]);
    assert.deepEqual(await page.evaluate(()=>Object.keys(localStorage)),[]);
    await page.goto(`${harness.baseURL}/documents/assurances/nouvelle?patientId=patient-demo-003`);
    await page.locator("#far-context").waitFor();
    for (const field of ["#far-purpose","#far-care-type","#far-context"])
      assert.equal(await page.locator(field).inputValue(),"");
    await page.getByPlaceholder("Description de l'acte...").first().fill("Acte fictif");
    await preview.click();
    await pdf.getByRole("alert").filter({hasText:"explicitement"}).waitFor();
  } finally { await value.close(); }
});
