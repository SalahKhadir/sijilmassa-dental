import assert from "node:assert/strict";
import { before, after, test } from "node:test";
import { PDFDocument } from "pdf-lib";
import { browserHarness } from "./browser-harness.mjs";
const harness = browserHarness({ port: 3107 });
before(harness.start);
after(harness.stop);
test("CNSS live draft previews two original pages, downloads, prints, invalidates and blocks overflow", async () => {
  const { value, page, errors, external } = await harness.context();
  try {
    await page.goto(`${harness.baseURL}/documents/assurances/draft-ins-demo-001`);
    const section = page.getByRole("region", { name: "PDF CNSS" });
    await section.getByRole("button", { name: "Prévisualiser", exact: true }).click();
    const link = section.getByRole("link", { name: "Télécharger le PDF" });
    await link.waitFor();
    const url = await link.getAttribute("href"); assert(url.startsWith("blob:"));
    const bytes = await page.evaluate(async url => Array.from(new Uint8Array(await (await fetch(url)).arrayBuffer())), url);
    const pdf = await PDFDocument.load(new Uint8Array(bytes));
    assert.equal(pdf.getPageCount(), 2);
    assert.equal(pdf.getPages()[0].getRotation().angle,270);
    assert.equal(pdf.getPages()[0].getWidth(),728.4);
    const download = page.waitForEvent("download"); await link.click();
    assert.equal((await download).suggestedFilename(),"feuille-soins-cnss.pdf");
    const print = section.getByRole("button",{ name:"Imprimer", exact:true });
    await page.waitForFunction(() => !Array.from(document.querySelectorAll("button")).find(b=>b.textContent==="Imprimer")?.disabled);
    await page.evaluate(() => {
      window.__cnssPrintCalls=0;
      document.querySelector('iframe[title*="PDF CNSS"]').contentWindow.print=()=>window.__cnssPrintCalls++;
    });
    await print.click();
    assert.equal(await page.evaluate(()=>window.__cnssPrintCalls),1);
    await section.getByRole("status").waitFor();
    await page.screenshot({path:"/tmp/cnss-review/browser-preview.png",fullPage:true});
    await page.locator("#decl-place").fill("Rabat fictif");
    assert.equal(await link.count(),0);
    assert(await print.isDisabled());
    assert(await page.evaluate(async url => { try { await fetch(url); return false; } catch { return true; } },url));
    await section.getByRole("button",{name:"Prévisualiser",exact:true}).click();
    await link.waitFor();
    assert.notEqual(await link.getAttribute("href"),url);
    const fee = page.locator("tbody tr").first().locator('input[type="number"]').last();
    await fee.fill("0");
    assert.equal(await fee.inputValue(),"0.00");
    await fee.fill("");
    await page.locator("#decl-place").fill("");
    await page.locator("#decl-date").fill("");
    await page.locator("#decl-attach").fill("");
    await section.getByRole("button",{name:"Prévisualiser",exact:true}).click();
    await link.waitFor();
    await section.getByText("Montant des frais : non renseigné, laissé vide.",{exact:true}).waitFor();
    await section.getByText("Nombre de pièces jointes : non renseigné, laissé vide.",{exact:true}).waitFor();
    const add=page.getByRole("button",{name:/Ajouter une ligne/});
    await add.click(); await add.click();
    await page.getByPlaceholder("Description de l'acte...").nth(2).fill("Acte fictif trois");
    await page.getByPlaceholder("Description de l'acte...").nth(3).fill("Acte fictif quatre");
    await section.getByRole("button",{name:"Prévisualiser",exact:true}).click();
    await section.getByRole("alert").filter({hasText:"1 à 3 actes"}).waitFor();
    assert.equal(await link.count(),0);
    assert.deepEqual(await page.evaluate(()=>Object.keys(localStorage)),[]);
    assert.deepEqual(errors,[]);
    assert.deepEqual(external.filter(u=>!u.startsWith("blob:")),[]);
    await page.goto(`${harness.baseURL}/documents/assurances/draft-ins-demo-002`);
    await page.getByRole("heading",{name:/Feuille de soins dentaires/}).waitFor();
    assert.equal(await page.getByRole("region",{name:"PDF CNSS"}).count(),0);
  } finally { await value.close(); }
});

test("dentist confirms, removes, clears and saves chart marks; changes revoke the PDF preview", async () => {
  const { value, page, errors, external } = await harness.context();
  try {
    await page.goto(`${harness.baseURL}/documents/assurances/draft-ins-demo-001`);
    const chart = page.getByRole("region", { name: "Schéma dentaire", exact: true });
    const pdf = page.getByRole("region", { name: "PDF CNSS" });
    const tooth = number => chart.getByRole("checkbox", { name: `Confirmer la dent FDI ${number}`, exact: true });
    await chart.waitFor();
    assert.equal(await chart.locator("rect[data-tooth]").count(),0);
    assert.equal(await chart.getByRole("checkbox").count(),52);
    await tooth(16).check(); await tooth(11).check();
    assert.deepEqual(await chart.locator("rect[data-tooth]").evaluateAll(nodes=>nodes.map(n=>n.dataset.tooth)),["11","16"]);
    await pdf.getByRole("button", {name:"Prévisualiser",exact:true}).click();
    const link = pdf.getByRole("link", {name:"Télécharger le PDF"});
    await link.waitFor(); const oldUrl = await link.getAttribute("href");
    await tooth(16).uncheck();
    assert.equal(await link.count(),0);
    assert.equal(await chart.locator('rect[data-tooth="16"]').count(),0);
    assert.equal(await chart.locator('rect[data-tooth="11"]').count(),1);
    assert(await page.evaluate(async url=>{try {await fetch(url);return false;} catch{return true;}},oldUrl));
    await chart.getByRole("button",{name:"Effacer les marques",exact:true}).click();
    assert.equal(await chart.locator("rect[data-tooth]").count(),0);
    for (const number of [16,11,51,61,71,81]) await tooth(number).check();
    await page.screenshot({path:"/tmp/cnss-chart/browser-selection.png",fullPage:true});
    await page.getByRole("button",{name:"Enregistrer en brouillon",exact:true}).click();
    await page.waitForURL("**/patients/patient-demo-001");
    await page.locator('a[href="/documents/assurances/draft-ins-demo-001"]').click();
    await chart.waitFor();
    for (const number of [16,11,51,61,71,81]) assert(await tooth(number).isChecked());
    assert.equal(await chart.locator("rect[data-tooth]").count(),6);
    assert.equal(await page.getByPlaceholder("Description de l'acte...").first().inputValue(),"Obturation composite 3 faces");
    assert(await page.locator("#draft-patient").isDisabled());
    // New drafts allow a beneficiary change; confirmed marks must not carry over.
    await page.goto(`${harness.baseURL}/documents/assurances/nouvelle?patientId=patient-demo-001`);
    await chart.waitFor();
    await tooth(16).check();
    await page.locator("#draft-patient").selectOption("patient-demo-002");
    await page.waitForFunction(() => document.querySelector("#draft-provider").value === "CNOPS");
    await page.locator("#draft-provider").selectOption("CNSS");
    await chart.waitFor();
    assert.equal(await chart.locator("rect[data-tooth]").count(),0);
    assert.deepEqual(errors,[]);
    assert.deepEqual(external.filter(url=>!url.startsWith("blob:")),[]);
  } finally { await value.close(); }
});
